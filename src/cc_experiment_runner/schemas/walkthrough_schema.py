"""
Pydantic schema for walkthrough JSON structure.

Defines the structure of walkthrough JSON files generated by the walkthrough generator.
"""

from typing import Optional, List
from pydantic import BaseModel, Field


class WalkthroughMetadata(BaseModel):
    """Metadata about the walkthrough."""
    title: str = Field(..., description="Walkthrough title")
    description: Optional[str] = Field(None, description="Walkthrough description")
    library: str = Field(..., description="Library name (e.g., 'FastAPI')")
    version: str = Field(..., description="Library version")
    createdAt: int = Field(..., description="Unix timestamp (milliseconds)")
    updatedAt: int = Field(..., description="Unix timestamp (milliseconds)")
    originalDocPath: Optional[str] = Field(None, description="Path to original documentation")
    generatedBy: str = Field(default="cc-experiment-walkthrough-generator", description="Generator identifier")


class WalkthroughStep(BaseModel):
    """Individual step in the walkthrough."""
    displayOrder: int = Field(..., description="Step order (1-indexed)")
    contentForUser: str = Field(..., description="Markdown content for users to read")
    contextForAgent: str = Field(..., description="Background context for the agent")
    operationsForAgent: str = Field(..., description="Executable commands and operations")
    introductionForAgent: str = Field(..., description="Step purpose and goals")

    # Optional fields
    nextStepReference: Optional[int] = Field(None, description="Display order of next step (null for last step)")
    createdAt: Optional[int] = Field(None, description="Unix timestamp (milliseconds)")
    updatedAt: Optional[int] = Field(None, description="Unix timestamp (milliseconds)")


class Walkthrough(BaseModel):
    """Complete walkthrough structure."""
    walkthrough: WalkthroughMetadata = Field(..., description="Walkthrough metadata")
    steps: List[WalkthroughStep] = Field(..., min_length=1, description="List of walkthrough steps")

    class Config:
        json_schema_extra = {
            "example": {
                "walkthrough": {
                    "title": "Getting Started with FastAPI",
                    "description": "Learn to build your first FastAPI application",
                    "library": "FastAPI",
                    "version": "0.100",
                    "createdAt": 1700000000000,
                    "updatedAt": 1700000000000,
                    "originalDocPath": "docs/tutorial/first-steps.md",
                    "generatedBy": "cc-experiment-walkthrough-generator"
                },
                "steps": [
                    {
                        "displayOrder": 1,
                        "contentForUser": "# Step 1: Install FastAPI\n\nInstall FastAPI and uvicorn...",
                        "contextForAgent": "FastAPI requires Python 3.7+ and pip...",
                        "operationsForAgent": "```bash\npip install fastapi uvicorn\n```",
                        "introductionForAgent": "Install FastAPI framework and ASGI server",
                        "nextStepReference": 2,
                        "createdAt": 1700000000000,
                        "updatedAt": 1700000000000
                    }
                ]
            }
        }

    def to_json_schema(self) -> dict:
        """Export as JSON schema for validation."""
        return self.model_json_schema()
